def seed_data(db: Session) -> None:
    for row in DRIVERS:
        db.add(Driver(**row))
    db.flush()

    for row in SHIPMENTS:
        events = row["events"]
        payload = {key: value for key, value in row.items() if key != "events"}
        shipment = Shipment(**payload)
        db.add(shipment)
        db.flush()
        for timestamp, location, message in events:
            db.add(
                ShipmentEvent(
                    shipment_id=shipment.id,
                    timestamp=_dt(timestamp),
                    location=location,
                    message=message,
                )
            )


def seed_if_empty(db: Session) -> None:
    existing = db.scalar(select(Shipment.id).limit(1))
    if existing is not None:
        return
    seed_data(db)
    db.commit()
